CREATE DATABASE IF NOT EXISTS isw613 CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE isw613;
CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, full_name VARCHAR(100) NOT NULL,
 username VARCHAR(50) NOT NULL UNIQUE, email VARCHAR(100) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS careers (id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS courses (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(150) NOT NULL,
 course_code VARCHAR(30) NOT NULL UNIQUE, career_id INT NOT NULL,
 credits TINYINT UNSIGNED NOT NULL, description TEXT NOT NULL,
 CONSTRAINT fk_courses_careers FOREIGN KEY(career_id) REFERENCES careers(id)
 ON UPDATE CASCADE ON DELETE RESTRICT
);
